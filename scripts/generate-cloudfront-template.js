const fs = require("fs");
const path = require("path");

// "ap-northeast-1" -> "ApNortheast1"
function pascal(region) {
  return region
    .split("-")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");
}

function functionResource(region, secretName) {
  const name = pascal(region);
  return `  ${name}AppendKeyFunction:
    Type: AWS::CloudFront::Function
    Properties:
      Name: !Sub "\${AWS::StackName}-${name}-AppendKey"
      AutoPublish: true
      FunctionConfig:
        Comment: Inject ${region} Location API Key and strip region prefix
        Runtime: cloudfront-js-2.0
      FunctionCode: !Sub
        - |
          function handler(event) {
            var request = event.request;
            request.uri = request.uri.slice('/${region}'.length);
            request.querystring['key'] = { value: '\${ApiKeyValue}' };
            return request;
          }
        - ApiKeyValue: !Sub "{{resolve:secretsmanager:${secretName}:SecretString:${region}}}"
`;
}

function originResource(region) {
  const name = pascal(region);
  return `          - Id: ${name}Origin
            DomainName: maps.geo.${region}.amazonaws.com
            CustomOriginConfig:
              OriginProtocolPolicy: https-only
              OriginSSLProtocols: [TLSv1.2]
`;
}

function behaviorResource(region) {
  const name = pascal(region);
  return `          - PathPattern: /${region}/*
            TargetOriginId: ${name}Origin
            ViewerProtocolPolicy: https-only
            CachePolicyId: !Ref CachePolicy
            OriginRequestPolicyId: !Ref OriginRequestPolicy
            AllowedMethods: [GET, HEAD]
            CachedMethods: [GET, HEAD]
            Compress: true
            FunctionAssociations:
              - EventType: viewer-request
                FunctionARN: !GetAtt ${name}AppendKeyFunction.FunctionMetadata.FunctionARN
`;
}

function buildTemplate(regions, secretName) {
  const functions = regions.map((r) => functionResource(r, secretName)).join("\n");
  const origins = regions.map(originResource).join("");
  const behaviors = regions.map(behaviorResource).join("");
  const firstName = pascal(regions[0]);
  return `AWSTemplateFormatVersion: "2010-09-09"
Description: CloudFront proxy for ALS map tiles (multi-region) - GENERATED, do not edit by hand

# Generated by scripts/generate-cloudfront-template.js from the mapping file regions:
#   ${regions.join(", ")}

Resources:
${functions}
  CachePolicy:
    Type: AWS::CloudFront::CachePolicy
    Properties:
      CachePolicyConfig:
        Name: !Sub "\${AWS::StackName}-MapTileCache"
        DefaultTTL: 86400
        MaxTTL: 604800
        MinTTL: 3600
        ParametersInCacheKeyAndForwardedToOrigin:
          CookiesConfig: { CookieBehavior: none }
          HeadersConfig: { HeaderBehavior: none }
          QueryStringsConfig: { QueryStringBehavior: none }
          EnableAcceptEncodingGzip: true
          EnableAcceptEncodingBrotli: true

  OriginRequestPolicy:
    Type: AWS::CloudFront::OriginRequestPolicy
    Properties:
      OriginRequestPolicyConfig:
        Name: !Sub "\${AWS::StackName}-ForwardApiKey"
        CookiesConfig: { CookieBehavior: none }
        HeadersConfig: { HeaderBehavior: none }
        QueryStringsConfig:
          QueryStringBehavior: whitelist
          QueryStrings: [key]

  Distribution:
    Type: AWS::CloudFront::Distribution
    Properties:
      DistributionConfig:
        Enabled: true
        Comment: ALS Map Tile Proxy (multi-region)
        DefaultCacheBehavior:
          TargetOriginId: ${firstName}Origin
          ViewerProtocolPolicy: https-only
          CachePolicyId: !Ref CachePolicy
          OriginRequestPolicyId: !Ref OriginRequestPolicy
          AllowedMethods: [GET, HEAD]
          CachedMethods: [GET, HEAD]
          Compress: true
          FunctionAssociations:
            - EventType: viewer-request
              FunctionARN: !GetAtt ${firstName}AppendKeyFunction.FunctionMetadata.FunctionARN
        CacheBehaviors:
${behaviors}        Origins:
${origins}
Outputs:
  CloudFrontDomain:
    Description: Use this as MAP_TILE_DOMAIN environment variable
    Value: !GetAtt Distribution.DomainName
`;
}

function main() {
  // The mapping file is the single source of truth for the region set.
  // MAPPING_FILE lets callers point at the example (e.g. in CI) if the real
  // file isn't present yet.
  const { createMappingStore } = require("../src/mappingStore");
  const mappingFile =
    process.env.MAPPING_FILE ||
    path.join(__dirname, "..", "config", "country-region-map.json");
  const secretName = process.env.LOCATION_API_KEYS_SECRET_NAME || "location-proxy/api-keys";

  const regions = [...createMappingStore(mappingFile).regions];
  if (!regions.length) {
    console.error(`Mapping file ${mappingFile} declares no regions`);
    process.exit(1);
  }
  const out = path.join(__dirname, "..", "infra", "cloudfront-map-proxy.yaml");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, buildTemplate(regions, secretName));
  console.log(`Wrote ${out} for regions: ${regions.join(", ")}`);
}

if (require.main === module) main();

module.exports = { buildTemplate, pascal };
